function getLocale(req) {
  if (req.session?.locale) return req.session.locale;
  const cookie = (req.headers.cookie || '').split(';').map((part) => part.trim()).find((part) => part.startsWith('locale='));
  return cookie ? decodeURIComponent(cookie.split('=')[1]) : 'fr';
}

module.exports = {
  getLocale,
  middleware(req, res, next) {
    const locale = ['fr', 'en'].includes(getLocale(req)) ? getLocale(req) : 'fr';
    req.session.locale = locale;
    res.locals.locale = locale;
    res.locals.t = (key) => translations[locale][key] || translations.fr[key] || key;
    res.locals.translations = translations[locale];
    next();
  },
  translations
};
